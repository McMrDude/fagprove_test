
-- Kursbedriften AS
-- Database schema for a new, empty Supabase PostgreSQL database.
-- Run this only when the seven tables do not already exist.

-- =====================================================
-- 1. USERS
-- Stores teachers and office-worker accounts.
-- =====================================================

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    name text NOT NULL,
    password_hash text,
    phone_number text,
    email text NOT NULL,
    role text NOT NULL DEFAULT 'teacher'
);

-- =====================================================
-- 2. PARTICIPANTS
-- Stores course participants.
-- =====================================================

CREATE TABLE public.participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    phone_number text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- =====================================================
-- 3. COURSES
-- Stores subjects and their assigned teachers.
-- =====================================================

CREATE TABLE public.courses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    teacher_id bigint,
    start_date date,
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT courses_teacher_id_fkey
        FOREIGN KEY (teacher_id)
        REFERENCES public.users(id)
);

-- =====================================================
-- 4. COURSE OFFERINGS
-- Stores individual planned or completed runs of a subject.
-- =====================================================

CREATE TABLE public.course_offerings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    status text NOT NULL DEFAULT 'planned',

    CONSTRAINT course_offerings_course_id_fkey
        FOREIGN KEY (course_id)
        REFERENCES public.courses(id),

    CONSTRAINT course_offerings_status_check
        CHECK (status IN ('planned', 'active', 'completed'))
);

CREATE INDEX idx_course_offerings_course_id
    ON public.course_offerings(course_id);

-- =====================================================
-- 5. COURSE SESSIONS
-- Stores the individual dates for each course offering.
-- =====================================================

CREATE TABLE public.course_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL,
    session_number integer NOT NULL,
    session_date date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    offering_id bigint,

    CONSTRAINT course_sessions_course_id_fkey
        FOREIGN KEY (course_id)
        REFERENCES public.courses(id),

    CONSTRAINT course_sessions_offering_id_fkey
        FOREIGN KEY (offering_id)
        REFERENCES public.course_offerings(id),

    CONSTRAINT course_sessions_offering_id_session_number_key
        UNIQUE (offering_id, session_number)
);

CREATE INDEX idx_course_session_offering_id
    ON public.course_sessions(offering_id);

-- =====================================================
-- 6. COURSE PARTICIPANTS
-- Connects participants to courses and tracks completion.
-- =====================================================

CREATE TABLE public.course_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id bigint NOT NULL,
    participant_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    offering_id bigint,
    completion_status text NOT NULL DEFAULT 'enrolled',
    completion_reviewed_at timestamptz,
    completion_reviewed_by bigint,
    completion_note text,

    CONSTRAINT course_participants_course_id_fkey
        FOREIGN KEY (course_id)
        REFERENCES public.courses(id),

    CONSTRAINT course_participants_offering_id_fkey
        FOREIGN KEY (offering_id)
        REFERENCES public.course_offerings(id),

    CONSTRAINT course_participants_participant_id_fkey
        FOREIGN KEY (participant_id)
        REFERENCES public.participants(id),

    CONSTRAINT course_participants_completion_status_check
        CHECK (
            completion_status IN (
                'enrolled',
                'pending_review',
                'completed',
                'not_completed'
            )
        ),

    CONSTRAINT course_participants_course_id_participant_id_key
        UNIQUE (course_id, participant_id)
);

CREATE INDEX idx_course_participants_offering_id
    ON public.course_participants(offering_id);

-- =====================================================
-- 7. ATTENDANCE
-- Stores attendance for each participant and session.
-- =====================================================

CREATE TABLE public.attendance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id bigint NOT NULL,
    participant_id bigint NOT NULL,
    present boolean NOT NULL DEFAULT false,
    marked_at timestamptz,

    CONSTRAINT attendance_session_id_fkey
        FOREIGN KEY (session_id)
        REFERENCES public.course_sessions(id),

    CONSTRAINT attendance_participant_id_fkey
        FOREIGN KEY (participant_id)
        REFERENCES public.participants(id),

    CONSTRAINT attendance_session_id_participant_id_key
        UNIQUE (session_id, participant_id)
);

-- =====================================================
